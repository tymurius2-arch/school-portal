// Фільтр поганих слів: слово замінюється першою літерою й зірочками.
// Шукаємо лише з початку слова, щоб не чіпати звичайні слова («корабля», «небагато»).
const ROOTS = [
  "ху[йяеєюиі]", "хуё", "пизд", "пізд", "бля[дтхь]?", "[её]б[ауаи]", "єба", "їб[аулн]", "[её]бл", "[её]бн", "уеб", "уёб", "заеб", "заїб", "наху", "поху",
  "мудак", "мудил", "муда[кч]", "підар", "пидор", "пидар", "педик", "гандон", "залуп", "дроч", "шлюх", "сучк", "сучар", "гівн[оа]", "говн[оа]",
  "fuck", "shit", "bitch", "dick", "cunt"
];
const WORDS = ["сука", "суки", "суку", "сукою", "сучка", "срака", "сраку", "жопа", "жопу", "жопі", "лох", "лохи", "дебіл", "дебил", "ідіот", "идиот", "тупиця", "чмо"];
const RE = new RegExp(`(?<![\\p{L}])(?:(?:${ROOTS.join("|")})\\p{L}*|(?:${WORDS.join("|")})(?![\\p{L}]))`, "giu");
export const clean = text => String(text || "").replace(RE, w => w[0] + "*".repeat(Math.max(2, w.length - 1)));
export const isDirty = text => { RE.lastIndex = 0; return RE.test(String(text || "")); };
